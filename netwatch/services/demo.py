    ("Accounts Wi-Fi AP (demo)", "10.10.1.10", "access_point", "Accounts office", "flaky"),
    ("Branch VPN Firewall (demo)", "10.10.9.1", "firewall", "Ikeja branch", "degraded"),
    ("Reception Printer (demo)", "10.10.2.50", "printer", "Reception", "stable"),
